-- Giải đấu (competitions) feature.
--
-- Club members are rows in public.users; opponent players only exist as free
-- text on lineups and match events, so every "player" column comes in a pair:
-- a nullable user_id for our own players and a nullable name for everybody else.
--
-- Apply with the Supabase SQL editor (or `supabase db push`), then run
-- `npm run type:generate` to refresh database.types.ts.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

-- security definer so the check works even when RLS hides other users' rows.
create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.users u
    where u.id = auth.uid() and u.role = 'ADMIN'
  );
$$;

-- ---------------------------------------------------------------------------
-- Schema
-- ---------------------------------------------------------------------------

alter table public.users
  add column if not exists shirt_number smallint;

create table if not exists public.competitions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  season text,
  legs smallint not null default 1,
  team_count smallint,
  start_date date,
  end_date date,
  venue text,
  organizer text,
  status text not null default 'ongoing'
    check (status in ('upcoming', 'ongoing', 'finished'))
);

create table if not exists public.competition_teams (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  competition_id bigint not null references public.competitions (id) on delete cascade,
  name text not null,
  abbr text,
  is_own_team boolean not null default false,
  unique (competition_id, name)
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  competition_id bigint not null references public.competitions (id) on delete cascade,
  round smallint,
  match_date date not null,
  kickoff_time time,
  venue text,
  referee text,
  home_team_id bigint not null references public.competition_teams (id) on delete cascade,
  away_team_id bigint not null references public.competition_teams (id) on delete cascade,
  home_score smallint,
  away_score smallint,
  status text not null default 'finished'
    check (status in ('scheduled', 'live', 'finished')),
  check (home_team_id <> away_team_id)
);

create table if not exists public.match_lineups (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  match_id bigint not null references public.matches (id) on delete cascade,
  competition_team_id bigint not null references public.competition_teams (id) on delete cascade,
  user_id uuid references public.users (id) on delete set null,
  player_name text,
  shirt_number smallint,
  position text,
  is_starter boolean not null default true,
  check (user_id is not null or player_name is not null)
);

create table if not exists public.match_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  match_id bigint not null references public.matches (id) on delete cascade,
  competition_team_id bigint not null references public.competition_teams (id) on delete cascade,
  minute smallint,
  type text not null default 'goal'
    check (type in ('goal', 'own_goal', 'substitution', 'yellow_card', 'red_card')),
  player_user_id uuid references public.users (id) on delete set null,
  player_name text,
  assist_user_id uuid references public.users (id) on delete set null,
  assist_name text,
  note text,
  check (player_user_id is not null or player_name is not null)
);

create table if not exists public.motm_votes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  match_id bigint not null references public.matches (id) on delete cascade,
  voter_id uuid not null default auth.uid() references public.users (id) on delete cascade,
  player_user_id uuid references public.users (id) on delete cascade,
  player_name text,
  unique (match_id, voter_id),
  check (player_user_id is not null or player_name is not null)
);

create index if not exists competition_teams_competition_id_idx on public.competition_teams (competition_id);
create index if not exists matches_competition_id_idx on public.matches (competition_id);
create index if not exists match_lineups_match_id_idx on public.match_lineups (match_id);
create index if not exists match_lineups_user_id_idx on public.match_lineups (user_id);
create index if not exists match_events_match_id_idx on public.match_events (match_id);
create index if not exists match_events_player_user_id_idx on public.match_events (player_user_id);
create index if not exists match_events_assist_user_id_idx on public.match_events (assist_user_id);
create index if not exists motm_votes_match_id_idx on public.motm_votes (match_id);

-- ---------------------------------------------------------------------------
-- Row level security: everybody signed in can read, only admins can write.
-- ---------------------------------------------------------------------------

-- Supabase grants these by default privilege; repeat it so the migration also
-- works on projects where the default privileges were changed.
grant select, insert, update, delete on
  public.competitions,
  public.competition_teams,
  public.matches,
  public.match_lineups,
  public.match_events,
  public.motm_votes
to authenticated;

grant usage, select on all sequences in schema public to authenticated;

alter table public.competitions enable row level security;
alter table public.competition_teams enable row level security;
alter table public.matches enable row level security;
alter table public.match_lineups enable row level security;
alter table public.match_events enable row level security;
alter table public.motm_votes enable row level security;

do $$
declare
  t text;
begin
  foreach t in array array[
    'competitions', 'competition_teams', 'matches', 'match_lineups', 'match_events'
  ] loop
    execute format('drop policy if exists %I on public.%I', t || '_read', t);
    execute format('drop policy if exists %I on public.%I', t || '_write', t);
    execute format(
      'create policy %I on public.%I for select to authenticated using (true)',
      t || '_read', t
    );
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t || '_write', t
    );
  end loop;
end;
$$;

-- Voting is open to every signed in member, but only for their own vote.
drop policy if exists motm_votes_read on public.motm_votes;
create policy motm_votes_read on public.motm_votes
  for select to authenticated using (true);

drop policy if exists motm_votes_write on public.motm_votes;
create policy motm_votes_write on public.motm_votes
  for all to authenticated
  using (voter_id = auth.uid())
  with check (voter_id = auth.uid());

