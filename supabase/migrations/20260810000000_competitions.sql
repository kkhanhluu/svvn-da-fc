create or replace function public.get_competition_standings(p_competition_id bigint)
returns table (
  team_id bigint,
  team_name text,
  abbr text,
  is_own_team boolean,
  played bigint,
  won bigint,
  drawn bigint,
  lost bigint,
  goals_for bigint,
  goals_against bigint,
  goal_diff bigint,
  points bigint
)
language sql
stable
as $$
  with results as (
    select m.home_team_id as team, m.home_score as scored, m.away_score as conceded
    from public.matches m
    where m.competition_id = p_competition_id
      and m.status = 'finished'
      and m.home_score is not null
      and m.away_score is not null
    union all
    select m.away_team_id, m.away_score, m.home_score
    from public.matches m
    where m.competition_id = p_competition_id
      and m.status = 'finished'
      and m.home_score is not null
      and m.away_score is not null
  ),
  totals as (
    select
      t.id as team,
      t.name as label,
      t.abbr as short,
      t.is_own_team as own,
      count(r.team)::bigint as p,
      (count(*) filter (where r.scored > r.conceded))::bigint as w,
      (count(*) filter (where r.scored = r.conceded))::bigint as d,
      (count(*) filter (where r.scored < r.conceded))::bigint as l,
      coalesce(sum(r.scored), 0)::bigint as gf,
      coalesce(sum(r.conceded), 0)::bigint as ga
    from public.competition_teams t
    left join results r on r.team = t.id
    where t.competition_id = p_competition_id
    group by t.id, t.name, t.abbr, t.is_own_team
  )
  select
    s.team,
    s.label,
    s.short,
    s.own,
    s.p,
    s.w,
    s.d,
    s.l,
    s.gf,
    s.ga,
    s.gf - s.ga,
    s.w * 3 + s.d
  from totals s
  order by s.w * 3 + s.d desc, s.gf - s.ga desc, s.gf desc, s.label;
$$;

create or replace function public.get_competition_scorers(p_competition_id bigint)
returns table (
  player_key text,
  player_name text,
  user_id uuid,
  team_name text,
  goals bigint,
  assists bigint
)
language sql
stable
as $$
  with contributions as (
    select e.competition_team_id as team, e.player_user_id as uid, e.player_name as label, 1 as g, 0 as a
    from public.match_events e
    join public.matches m on m.id = e.match_id
    where m.competition_id = p_competition_id and e.type = 'goal'
    union all
    select e.competition_team_id, e.assist_user_id, e.assist_name, 0, 1
    from public.match_events e
    join public.matches m on m.id = e.match_id
    where m.competition_id = p_competition_id
      and e.type = 'goal'
      and (e.assist_user_id is not null or e.assist_name is not null)
  ),
  totals as (
    select
      coalesce(c.uid::text, c.label) as key,
      coalesce(
        nullif(trim(concat_ws(' ', u.first_name, u.last_name)), ''),
        c.label
      ) as label,
      c.uid as uid,
      t.name as team,
      sum(c.g)::bigint as g,
      sum(c.a)::bigint as a
    from contributions c
    left join public.users u on u.id = c.uid
    left join public.competition_teams t on t.id = c.team
    group by 1, 2, 3, 4
  )
  select s.key, s.label, s.uid, s.team, s.g, s.a
  from totals s
  where s.key is not null
  order by s.g desc, s.a desc, s.label;
$$;

create or replace function public.get_squad_stats()
returns table (
  user_id uuid,
  first_name text,
  last_name text,
  player_position text,
  shirt_number smallint,
  apps bigint,
  goals bigint,
  assists bigint
)
language sql
stable
as $$
  select s.id, s.first, s.last, s.pos, s.shirt, s.apps, s.goals, s.assists
  from (
    select
      u.id as id,
      u.first_name as first,
      u.last_name as last,
      u.position as pos,
      u.shirt_number as shirt,
      (
        select count(distinct l.match_id)
        from public.match_lineups l
        where l.user_id = u.id
      )::bigint as apps,
      (
        select count(*)
        from public.match_events e
        where e.player_user_id = u.id and e.type = 'goal'
      )::bigint as goals,
      (
        select count(*)
        from public.match_events e
        where e.assist_user_id = u.id and e.type = 'goal'
      )::bigint as assists
    from public.users u
  ) s
  order by s.shirt nulls last, s.first, s.last;
$$;

create or replace function public.get_player_competition_stats(p_user_id uuid)
returns table (
  competition_id bigint,
  competition_name text,
  apps bigint,
  goals bigint,
  assists bigint
)
language sql
stable
as $$
  select s.id, s.label, s.apps, s.goals, s.assists
  from (
    select
      c.id as id,
      c.name as label,
      c.start_date as started,
      (
        select count(distinct l.match_id)
        from public.match_lineups l
        join public.matches m on m.id = l.match_id
        where l.user_id = p_user_id and m.competition_id = c.id
      )::bigint as apps,
      (
        select count(*)
        from public.match_events e
        join public.matches m on m.id = e.match_id
        where e.player_user_id = p_user_id and e.type = 'goal' and m.competition_id = c.id
      )::bigint as goals,
      (
        select count(*)
        from public.match_events e
        join public.matches m on m.id = e.match_id
        where e.assist_user_id = p_user_id and e.type = 'goal' and m.competition_id = c.id
      )::bigint as assists
    from public.competitions c
  ) s
  where s.apps > 0 or s.goals > 0 or s.assists > 0
  order by s.started desc nulls last, s.label;
$$; 
